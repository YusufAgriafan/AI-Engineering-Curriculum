    "def sigmoid(z):\n",
    "    return 1.0 / (1.0 + np.exp(-np.clip(z, -30, 30)))\n",
    "\n",
    "def cos_sim(a, b):\n",
    "    return float(a @ b / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))\n",
