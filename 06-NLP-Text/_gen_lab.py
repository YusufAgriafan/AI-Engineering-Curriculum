    "    \"\"\"Skip-gram + negative sampling.\n",
    "    pairs        : list (target_id, context_id)\n",
    "    freq_unigram : array (vocab_size,) probabilitas unigram (untuk sampling noise)\n",
    "    Return (W_in, loss_history): W_in (vocab_size, dim) = embedding matrix.\n",
    "    \"\"\"\n",
    "    rng = np.random.default_rng(seed)\n",
    "    W_in = rng.normal(0, 0.1, (vocab_size, dim))\n",
    "    W_out = rng.normal(0, 0.1, (vocab_size, dim))\n",
    "    noise = np.asarray(freq_unigram, dtype=float) ** 0.75   # trik word2vec: ^0.75\n",
    "    noise = noise / noise.sum()\n",
    "    loss_hist = []\n",
    "    for ep in range(epochs):\n",
    "        lr_ep = lr * (1.0 - 0.5 * ep / epochs)              # lr decay linear\n",
    "        tot, cnt = 0.0, 0\n",
    "        for (t, c) in pairs:\n",
